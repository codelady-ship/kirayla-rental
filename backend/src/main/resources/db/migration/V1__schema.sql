-- Kirayla core schema. Portable between H2 (MODE=PostgreSQL, dev/test) and PostgreSQL (prod / Neon).

CREATE TABLE users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           VARCHAR(160) NOT NULL UNIQUE,
    password_hash   VARCHAR(100) NOT NULL,
    full_name       VARCHAR(120) NOT NULL,
    city            VARCHAR(60),
    bio             VARCHAR(600),
    avatar_url      VARCHAR(600),
    role            VARCHAR(16)  NOT NULL DEFAULT 'USER',
    enabled         BOOLEAN      NOT NULL DEFAULT TRUE,
    demo_read_only  BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE categories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug        VARCHAR(60)  NOT NULL UNIQUE,
    name_az     VARCHAR(80)  NOT NULL,
    name_en     VARCHAR(80)  NOT NULL,
    icon        VARCHAR(40)  NOT NULL,
    sort_order  INT          NOT NULL DEFAULT 0,
    active      BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE listings (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id      BIGINT        NOT NULL REFERENCES users (id),
    category_id   BIGINT        NOT NULL REFERENCES categories (id),
    title         VARCHAR(140)  NOT NULL,
    description   VARCHAR(4000) NOT NULL,
    city          VARCHAR(60)   NOT NULL,
    district      VARCHAR(80),
    daily_price   NUMERIC(10, 2) NOT NULL,
    deposit       NUMERIC(10, 2) NOT NULL DEFAULT 0,
    item_condition VARCHAR(20)  NOT NULL DEFAULT 'GOOD',
    min_days      INT           NOT NULL DEFAULT 1,
    max_days      INT           NOT NULL DEFAULT 30,
    status        VARCHAR(16)   NOT NULL DEFAULT 'ACTIVE',
    rating_avg    NUMERIC(3, 2) NOT NULL DEFAULT 0,
    review_count  INT           NOT NULL DEFAULT 0,
    created_at    TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_listings_category ON listings (category_id);
CREATE INDEX ix_listings_owner ON listings (owner_id);
CREATE INDEX ix_listings_city ON listings (city);
CREATE INDEX ix_listings_status ON listings (status);

CREATE TABLE listing_photos (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id   BIGINT       NOT NULL REFERENCES listings (id) ON DELETE CASCADE,
    url          VARCHAR(600) NOT NULL,
    storage_key  VARCHAR(300),
    credit       VARCHAR(200),
    credit_url   VARCHAR(600),
    sort_order   INT          NOT NULL DEFAULT 0
);
CREATE INDEX ix_photos_listing ON listing_photos (listing_id);

CREATE TABLE availability_blocks (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id  BIGINT       NOT NULL REFERENCES listings (id) ON DELETE CASCADE,
    start_date  DATE         NOT NULL,
    end_date    DATE         NOT NULL,
    note        VARCHAR(200),
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_blocks_listing ON availability_blocks (listing_id);

CREATE TABLE bookings (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id    BIGINT         NOT NULL REFERENCES listings (id),
    renter_id     BIGINT         NOT NULL REFERENCES users (id),
    start_date    DATE           NOT NULL,
    end_date      DATE           NOT NULL,
    days          INT            NOT NULL,
    daily_price   NUMERIC(10, 2) NOT NULL,
    rental_total  NUMERIC(10, 2) NOT NULL,
    deposit       NUMERIC(10, 2) NOT NULL DEFAULT 0,
    status        VARCHAR(16)    NOT NULL DEFAULT 'REQUESTED',
    message       VARCHAR(500),
    created_at    TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_bookings_listing_dates ON bookings (listing_id, start_date, end_date);
CREATE INDEX ix_bookings_renter ON bookings (renter_id);

CREATE TABLE reviews (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id  BIGINT        NOT NULL UNIQUE REFERENCES bookings (id),
    listing_id  BIGINT        NOT NULL REFERENCES listings (id),
    author_id   BIGINT        NOT NULL REFERENCES users (id),
    rating      INT           NOT NULL,
    comment     VARCHAR(1000) NOT NULL,
    created_at  TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_reviews_listing ON reviews (listing_id);

CREATE TABLE wishlist_items (
    user_id     BIGINT    NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    listing_id  BIGINT    NOT NULL REFERENCES listings (id) ON DELETE CASCADE,
    created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, listing_id)
);

CREATE TABLE conversations (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id       BIGINT    NOT NULL REFERENCES listings (id),
    renter_id        BIGINT    NOT NULL REFERENCES users (id),
    host_id          BIGINT    NOT NULL REFERENCES users (id),
    created_at       TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_message_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_conversation UNIQUE (listing_id, renter_id)
);

CREATE TABLE messages (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id  BIGINT        NOT NULL REFERENCES conversations (id) ON DELETE CASCADE,
    sender_id        BIGINT        NOT NULL REFERENCES users (id),
    body             VARCHAR(2000) NOT NULL,
    created_at       TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    read_at          TIMESTAMP
);
CREATE INDEX ix_messages_conversation ON messages (conversation_id);

CREATE TABLE reports (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    listing_id   BIGINT       NOT NULL REFERENCES listings (id),
    reporter_id  BIGINT       NOT NULL REFERENCES users (id),
    reason       VARCHAR(500) NOT NULL,
    status       VARCHAR(16)  NOT NULL DEFAULT 'OPEN',
    created_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);
